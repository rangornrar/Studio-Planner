export function getLabLanguage() {
  const lang = String(document.documentElement.lang || "fr").slice(0, 2).toLowerCase();
  return LAB_COPY[lang] ? lang : "fr";
}

export function labText(key, vars) {
  const bundle = LAB_COPY[getLabLanguage()];
  let value = bundle[key] !== undefined ? bundle[key] : LAB_COPY.fr[key];
  if (typeof value !== "string") return value;
  if (vars) {
    Object.keys(vars).forEach(function (name) {
      value = value.split(`{${name}}`).join(String(vars[name]));
    });
  }
  return value;
}
